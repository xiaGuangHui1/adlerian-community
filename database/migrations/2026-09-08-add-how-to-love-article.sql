## 六、总结：爱上别人的四步法

1. **从"她喜欢我吗"切到"她是谁"** —— 把注意力从她的态度转向她这个人。这是所有后续步骤的前提。这一步没走，后面都是空中楼阁。

2. **从"全有或全无"变成"走台阶"** —— 把"爱上"拆成最小单元。不要问"我爱上她了吗"，问"我想了解她更多一点吗"。每次只走一步。

3. **把恐惧和行动分开** —— 恐惧不会消失。不要在等恐惧消失的时候什么都不做。带着恐惧打字。每一次"怕了还做"都在重写你大脑里的数据库。

4. **给你的自我定义留一个位置** —— 在你的"要成功"之外，加一行"也在学习建立连接"。你不必拆掉你的人设，你只需在里面加一个房间。

---

**爱上别人不是你放弃控制。是把控制从"我绝不打开"变成"我开一条缝"。**

你不需要把门全拆了。你只需要在门边站一会儿。从门缝里往外看一下。看到外面有一个人在过她的生活——她的烦恼、她的喜好、她说话时眼神的变化。这些和你的恐惧无关，和你的自尊无关，和你是不是够好无关。它们只是她的。

