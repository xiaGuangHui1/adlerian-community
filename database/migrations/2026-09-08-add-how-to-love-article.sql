## 五、爱上的真伪检验

怎么判断你是真的"爱上她"了，还是再次掉进了"需要她"的坑？

### 5.1 三个核心指标

**指标一：注意力方向**
- 需要她：你在想"她有没有想我""她为什么不找我""她还喜欢我吗"——箭头都指向你自己
- 爱上她：你在想"她今天看起来好像有心事""她说的那个观点很有意思""我想知道她为什么喜欢那个"——箭头指向她

**指标二：接近动机的性质**
- 需要她：你找她是为了缓解自己的焦虑。她不回你更焦虑，你找得更频繁。接近是缓解剂。
- 爱上她：你找她是因为你想和她分享某个东西、想听她的看法、想让她知道你在想她。接近是表达。

**指标三：分离时的状态**
- 需要她：她不联系你，你难受，但难受的内容是"我是不是不被爱了"
- 爱上她：她不在，你确实想她，但想的内容是"不知道她那边怎么样了""如果她在就好了，这件事我想听听她怎么说"

