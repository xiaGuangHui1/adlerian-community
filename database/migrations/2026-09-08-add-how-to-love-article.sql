## 一、爱上一个人到底发生了什么

首先需要搞清楚"爱上"到底是什么。它不是一个开关，是一个过程。

### 1.1 斯滕伯格的爱情三角理论

斯滕伯格把完整的爱拆成三个组件：

| 组件 | 是什么 | 怎么产生的 |
|---|---|---|
| **激情** | 生理唤醒、强烈渴望、想到对方就心跳 | 自动产生，不需要意志参与 |
| **亲密** | 理解、分享、温暖、被看见的感觉 | 通过自我表露和回应性逐渐建立 |
| **承诺** | 短期：决定进入关系；长期：决定维持关系 | 纯粹的意志行为 |

**这三个组件各自的启动方式完全不同。**

激情是自动的——你看见一个人，心跳加速，不需要你做任何决定。你之前的案例里，激情是有的——她主动联系你时你开心，她被喜欢的感觉让你有生理唤醒。

亲密是互动中建立的——需要你表露自己，也需要你回应她的表露。这一层在你之前的案例里基本是零。

承诺是纯粹的选择——你决定"我要和这个人进入一段关系"。你之前做了一次选择（她推进你表白），但那个选择是被动的。你没有主动说"我要你"。

**你的"爱上"卡在了哪里？** 卡在了激情之后——你产生了心动的感觉（激情），但你从未往前走到亲密（不敢暴露自己），也没有做过一次真正的承诺（被动接受不等于主动选择）。

